int main() {
    try {
        const std::uint8_t unused = 0;
        for(const auto view : {am::ByteView{}, am::ByteView{&unused, 0}, am::ByteView{nullptr, 1},
             am::ByteView{nullptr, std::numeric_limits<std::size_t>::max()}}) {
            bool rejected = false;
            try { (void)am::deserialize_external_object_ref_bytes(view); }
            catch(const std::invalid_argument&) { rejected = true; }
            expect(rejected, "null AMXR view accepted");
        }
        golden_vectors();
        source_domains_and_remapping();
        encoder_validation_and_bounds();
        field_boundaries();
        identity_consistency_matrix();
        isolated_component_count_boundary();
        decoder_controls();
        deterministic_decoder_mutations();
        legacy_source_compatibility();
        std::cout << "external identity goldens, domains, remapping, bounds, corruption and compatibility: PASS\n";
        return 0;
    } catch(const std::exception& error) {
        std::cerr << error.what() << '\n';
        return 1;
    }
}
